-- Back-fill unit_price from the product catalog, then compute line and order totals.
UPDATE order_items oi JOIN products p ON oi.product_id = p.id SET oi.unit_price = p.price;
UPDATE order_items SET amount = quantity * unit_price;
UPDATE orders o
JOIN (SELECT order_id, SUM(amount) s FROM order_items GROUP BY order_id) t ON o.id = t.order_id
SET o.total_amount = t.s;
